export type UiMessageKey = keyof typeof messages

const localeLabels: Record<UiLocale, UiMessageKey> = {
  'ru-RU': 'language.ru',
  'kk-KZ': 'language.kk',
  'en-US': 'language.en',
}

export function isUiLocale(value: unknown): value is UiLocale {
  return typeof value === 'string' && UI_LOCALES.includes(value as UiLocale)
}

export function localeLabelKey(locale: UiLocale): UiMessageKey {
  return localeLabels[locale]
}

export function translateMessage(
  locale: UiLocale,
  key: UiMessageKey,
  values: TranslationValues = {},
): string {
  const template = messages[key][locale] ?? messages[key]['ru-RU']
  return Object.entries(values).reduce(
    (rendered, [name, value]) => rendered.replaceAll(`{${name}}`, String(value)),
    template,
  )
}

