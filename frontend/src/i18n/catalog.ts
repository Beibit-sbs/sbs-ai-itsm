const englishSourceMessages: Record<string, MessageSet> = {
  ...sharedEnglishMessages,
  ...adminEnglishMessages,
  ...operationsEnglishMessages,
}

export function translateSource(locale: UiLocale, source: string): string {
  const key = sourceKeys[source] ?? russianSourceKeys[source]
  if (key) return translateMessage(locale, key)
  const direct = sourceMessages[source]
  if (direct) return locale === 'ru-RU' ? source : direct[locale]
  const englishDirect = englishSourceMessages[source]
  if (englishDirect) return englishDirect[locale]

  let match = source.match(/^(\d+(?:[.,]\d+)?) ч$/)
  if (match) return translateMessage(locale, 'requests.hoursShort', { count: match[1] })
  match = source.match(/^(\d+) дн$/)
  if (match) {
    return translateMessage(locale, 'catalog.daysShortValue', { count: match[1] })
  }
  match = source.match(/^(\d+) запр\. · (.+)$/)
  if (match) {
    return translateMessage(locale, 'requests.demandShort', {
      count: match[1],
      value: match[2],
    })
  }
  match = source.match(/^(.+) · форма v(.+)$/)
  if (match) {
    return translateMessage(locale, 'requests.formVersion', {
      code: match[1],
      version: match[2],
    })
  }
  match = source.match(/^(.+) · эскалация L(\d+)$/)
  if (match) {
    return translateMessage(locale, 'requests.escalation', {
      date: match[1],
      level: match[2],
    })
  }
  match = source.match(/^Группа: (.+)$/)
  if (match) return translateMessage(locale, 'requests.groupValue', { value: match[1] })
  match = source.match(/^Ожидаемый срок: (.+)$/)
  if (match) {
    return translateMessage(locale, 'requests.expectedDeliveryValue', {
      value: match[1],
    })
  }
  match = source.match(/^(\d+) событий$/)
  if (match) return translateMessage(locale, 'requests.eventCount', { count: match[1] })
  match = source.match(/^Выполнить: (.+)$/)
  if (match) {
    return translateMessage(locale, 'requests.fulfillTitle', {
      title: translateSource(locale, match[1]),
    })
  }
  match = source.match(/^Добавить в избранное: (.+)$/)
  if (match) {
    return translateMessage(locale, 'catalog.favoriteAdd', {
      title: translateSource(locale, match[1]),
    })
  }
  match = source.match(/^Удалить из избранного: (.+)$/)
  if (match) {
    return translateMessage(locale, 'catalog.favoriteRemove', {
      title: translateSource(locale, match[1]),
    })
  }
  match = source.match(/^Подробнее: (.+)$/)
  if (match) {
    return translateMessage(locale, 'catalog.detailsFor', {
      title: translateSource(locale, match[1]),
    })
  }
  match = source.match(/^Создать заявку: (.+)$/)
  if (match) {
    return translateMessage(locale, 'catalog.createFor', {
      title: translateSource(locale, match[1]),
    })
  }
  return source
}
